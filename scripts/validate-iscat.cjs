const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const Module = require('node:module')
const ts = require('typescript')

const cache = new Map()
function loadSource(file) {
  const absolute = path.resolve(__dirname, '..', 'src', 'components', 'simulator', file + '.ts')
  if (cache.has(absolute)) return cache.get(absolute).exports
  const compiled = ts.transpileModule(fs.readFileSync(absolute, 'utf8'), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
  }).outputText
  const loaded = new Module(absolute, module)
  loaded.filename = absolute
  loaded.paths = Module._nodeModulePaths(path.dirname(absolute))
  cache.set(absolute, loaded)
  loaded.require = (name) => name.startsWith('./') ? loadSource(path.join(path.dirname(file), name)) : require(name)
  loaded._compile(compiled, absolute)
  return loaded.exports
}

const { createMissionStore } = loadSource('mission')
const { ISCAT_PLANS, iscatDronePose } = loadSource('iscat')
const tick = (store, seconds) => { for (let i = 0; i < seconds * 2; i++) store.advance(.5) }
const own = (store) => store.getSnapshot().network.reports.filter((report) => report.origin.startsWith('ISCAT-'))

const mission = createMissionStore()
mission.startIscatMonitoring()
assert.equal(mission.getSnapshot().iscat.monitoringStartedAt, null)
mission.deployIscat()
assert.equal(mission.getSnapshot().phase, 'idle') // HUGIN remains independent.
tick(mission, 3.5)
assert.equal(mission.getSnapshot().iscat.deployedCount, 0)
tick(mission, .5)
assert.equal(mission.getSnapshot().iscat.deployedCount, 1)
assert.deepEqual(iscatDronePose(4, 0).position.slice(0, 3).filter((_, i) => i !== 1), ISCAT_PLANS[0].position)
tick(mission, 20)
assert.equal(mission.getSnapshot().iscat.deployedCount, 3)
assert.equal(mission.getSnapshot().iscat.monitoringStartedAt, null)
mission.startIscatMonitoring()
tick(mission, 2)
assert.equal(own(mission).length, 1)
assert.equal(own(mission)[0].status, 'Almacenado')
assert.equal(own(mission)[0].location, 'munin-02')
mission.startNetwork()
assert.equal(own(mission)[0].status, 'En tránsito')
tick(mission, 2)
mission.pause()
const pausedClock = mission.getClock()
const pausedEvents = mission.getSnapshot().iscat.events.length
tick(mission, 6)
assert.equal(mission.getClock(), pausedClock)
assert.equal(mission.getSnapshot().iscat.events.length, pausedEvents)
mission.resume()
tick(mission, 4)
assert.equal(own(mission).length, 3)
assert.equal(mission.getSnapshot().iscat.indicationCount, 2)
assert.equal(own(mission).find((report) => report.id === 'RPT-ISCAT-02').requiresVerification, true)
assert.equal(own(mission).find((report) => report.id === 'RPT-ISCAT-01').requiresVerification, false)
assert.ok(own(mission).every((report) => report.priority === 'Sin priorizar'))
tick(mission, 8)
assert.equal(own(mission).filter((report) => report.status === 'Recibido').length, 3)
assert.equal(mission.getSnapshot().iscat.receivedAlerts, 2)
mission.reset()
assert.equal(mission.getSnapshot().iscat.deployedCount, 0)
assert.equal(mission.getSnapshot().iscat.events.length, 0)
assert.equal(mission.getSnapshot().network.reports.length, 0)
assert.equal(mission.getClock(), 0)

const isolated = createMissionStore()
isolated.deployIscat()
tick(isolated, 24)
isolated.startIscatMonitoring()
isolated.failLink()
tick(isolated, 2)
isolated.startNetwork()
tick(isolated, 3)
const west = () => own(isolated).find((report) => report.id === 'RPT-ISCAT-02')
assert.equal(west().status, 'Almacenado')
assert.equal(west().location, 'munin-05')
assert.equal(isolated.getSnapshot().network.messengerStatus, 'Asignado')
assert.equal(isolated.getSnapshot().iscat.receivedAlerts, 0)
tick(isolated, 10)
assert.equal(west().location, 'munin-05')
tick(isolated, 2)
assert.equal(west().location, 'messenger')
assert.notEqual(west().status, 'Recibido')
tick(isolated, 9)
assert.equal(west().location, 'munin-01')
assert.notEqual(west().status, 'Recibido')
tick(isolated, 2)
assert.equal(west().status, 'Recibido')
assert.ok(west().history.some((entry) => entry.includes('almacenamiento digital')))
assert.ok(isolated.getSnapshot().iscat.receivedAlerts >= 1)

console.log('ISCAT: despliegue, monitoreo, reportes, conectividad, mensajero, pausa y reinicio verificados.')
