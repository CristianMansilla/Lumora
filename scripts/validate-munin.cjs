const mission = createMissionStore()
mission.start()
for (let index = 0; index < 25; index++) mission.advance(.5)
assert.ok(mission.getSnapshot().recognizedIds.includes('north'))
assert.equal(mission.getSnapshot().network.reports[0].status, 'Almacenado')
mission.startNetwork()
const beforePause = mission.getTime()
mission.pause()
mission.advance(5)
assert.equal(mission.getTime(), beforePause)
mission.resume()
for (let index = 0; index < 62; index++) mission.advance(.5)
assert.equal(mission.getSnapshot().recognizedIds.length, 5)
assert.ok(mission.getSnapshot().network.reports.some((item) => item.status === 'Recibido'))
mission.reset()
assert.equal(mission.getSnapshot().phase, 'idle')
assert.equal(mission.getSnapshot().recognizedIds.length, 0)
assert.equal(mission.getSnapshot().network.reports.length, 0)
assert.equal(mission.getSnapshot().network.events.length, 0)
