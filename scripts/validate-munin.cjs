const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const Module = require('node:module')
const ts = require('typescript')

const cache = new Map()
function loadSource(file) {
  const absolute = path.resolve(__dirname, '..', 'src', 'components', 'simulator', file + '.ts')
  if (cache.has(absolute)) return cache.get(absolute).exports
  const compiled = ts.transpileModule(fs.readFileSync(absolute, 'utf8'), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
  }).outputText
  const loaded = new Module(absolute, module)
  loaded.filename = absolute
  loaded.paths = Module._nodeModulePaths(path.dirname(absolute))
  cache.set(absolute, loaded)
  loaded.require = (name) => name.startsWith('./') ? loadSource(path.join(path.dirname(file), name)) : require(name)
  loaded._compile(compiled, absolute)
  return loaded.exports
}

const { route, createNetworkModel } = loadSource('network')
const { createMissionStore } = loadSource('mission')
const report = (model, id) => model.snapshot().reports.find((item) => item.id === id)

assert.deepEqual(route('munin-05', 'hub', false), ['munin-05', 'munin-01', 'hub'])
assert.equal(route('munin-05', 'hub', true), null)
assert.deepEqual(route('munin-03', 'hub', true), ['munin-03', 'munin-01', 'hub'])

const ordinary = createNetworkModel()
ordinary.onRecognized('north', 10)
assert.equal(report(ordinary, 'RPT-NORTH-01').status, 'Almacenado')
assert.equal(ordinary.snapshot(10).beacons[1].status, 'Disponible')
ordinary.start(10)
assert.equal(report(ordinary, 'RPT-NORTH-01').status, 'En tránsito')
assert.notEqual(report(ordinary, 'RPT-NORTH-01').location, 'hub')
ordinary.advance(12)
assert.notEqual(report(ordinary, 'RPT-NORTH-01').status, 'Recibido')
ordinary.advance(14)
assert.equal(report(ordinary, 'RPT-NORTH-01').status, 'Recibido')
assert.equal(report(ordinary, 'RPT-NORTH-01').location, 'hub')

