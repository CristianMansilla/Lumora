const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const Module = require('node:module')
const ts = require('typescript')

const cache = new Map()
function loadSource(file) {
  const absolute = path.resolve(__dirname, '..', 'src', 'components', 'simulator', file + '.ts')
  if (cache.has(absolute)) return cache.get(absolute).exports
  const compiled = ts.transpileModule(fs.readFileSync(absolute, 'utf8'), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
  }).outputText
  const loaded = new Module(absolute, module)
  loaded.filename = absolute
  loaded.paths = Module._nodeModulePaths(path.dirname(absolute))
  cache.set(absolute, loaded)
  loaded.require = (name) => name.startsWith('./') ? loadSource(path.join(path.dirname(file), name)) : require(name)
  loaded._compile(compiled, absolute)
  return loaded.exports
}

const { createNetworkModel } = loadSource('network')
const { ISCAT_PLANS } = loadSource('iscat')
const { deriveCollective } = loadSource('collective')
const { createMissionStore } = loadSource('mission')
const bySector = (view, id) => view.sectors.find((sector) => sector.sectorId === id)
const tick = (store, seconds) => { for (let index = 0; index < seconds * 2; index++) store.advance(.5) }

const network = createNetworkModel()
let view = deriveCollective(network.snapshot())
assert.equal(view.unknownCount, 5)
assert.equal(view.receivedCount, 0)
assert.equal(bySector(view, 'west').urgency, 'No evaluable')
assert.equal(view.resources.filter((item) => item.kind === 'Equipo de rescate' && item.sectorId).length, 0)

network.onRecognized('west', 0)
view = deriveCollective(network.snapshot())
assert.equal(view.unknownCount, 5)
assert.equal(view.localCount, 1)
network.start(0)
view = deriveCollective(network.snapshot())
assert.equal(view.transitCount, 1)
assert.equal(bySector(view, 'west').urgency, 'No evaluable')
network.advance(2)
assert.equal(bySector(deriveCollective(network.snapshot()), 'west').urgency, 'No evaluable')
network.advance(4)
view = deriveCollective(network.snapshot())
assert.equal(bySector(view, 'west').urgencyPoints, 4)
assert.equal(bySector(view, 'west').verification, 'Prioritaria')
assert.equal(view.changes.length, 1)
assert.ok(bySector(view, 'west').factors.some((factor) => factor.includes('Daño alto')))

network.fail(5, false)
network.addIscatReport(ISCAT_PLANS[1], 6)
view = deriveCollective(network.snapshot())
assert.equal(view.localCount, 1)
assert.equal(view.receivedCount, 1)
assert.equal(bySector(view, 'west').urgencyPoints, 4)
assert.equal(bySector(view, 'west').verification, 'Prioritaria')
assert.equal(view.changes.length, 1)
assert.equal(view.resources.find((item) => item.id === 'MÉDICA-01').sectorId, null)
assert.equal(network.snapshot().messengerStatus, 'Asignado')
network.advance(15)
network.advance(17)
assert.equal(network.snapshot().reports.find((item) => item.id === 'RPT-ISCAT-02').location, 'messenger')
assert.equal(bySector(deriveCollective(network.snapshot()), 'west').urgencyPoints, 4)
network.advance(24)
network.advance(26)
assert.equal(bySector(deriveCollective(network.snapshot()), 'west').urgencyPoints, 4)
network.advance(28)
view = deriveCollective(network.snapshot())
assert.equal(bySector(view, 'west').urgencyPoints, 9)
assert.equal(bySector(view, 'west').verification, 'Inmediata')
assert.equal(bySector(view, 'west').order, 1)
assert.equal(view.changes.length, 2)
assert.ok(view.changes[1].before.includes('Prioritaria'))
assert.ok(view.changes[1].after.includes('Inmediata'))
assert.ok(bySector(view, 'west').factors.some((factor) => factor.includes('posible patrón de auxilio')))
assert.equal(view.resources.find((item) => item.id === 'MÉDICA-01').sectorId, 'west')
assert.equal(new Set(view.resources.map((item) => item.id)).size, 4)
assert.equal(view.resources.length, 4)
assert.ok(view.resources.every((item) => item.reason && item.limitation))
assert.ok(view.resources.filter((item) => item.sectorId).every((item) => item.limitation.includes('ruta') || item.limitation.includes('acceso')))

const twoSectors = createNetworkModel()
twoSectors.onRecognized('west', 0)
twoSectors.onRecognized('south', 0)
twoSectors.start(0)
twoSectors.advance(2)
twoSectors.advance(4)
const rescueTargets = deriveCollective(twoSectors.snapshot()).resources.filter((item) => item.kind === 'Equipo de rescate').map((item) => item.sectorId)
assert.equal(new Set(rescueTargets).size, 2)
assert.deepEqual(new Set(rescueTargets), new Set(['west', 'south']))

const mission = createMissionStore()
mission.start()
tick(mission, 11)
assert.equal(mission.getSnapshot().collective.receivedCount, 0)
mission.startNetwork()
tick(mission, 4)
assert.ok(mission.getSnapshot().collective.receivedCount > 0)
mission.pause()
const beforePause = mission.getSnapshot().collective.changes.length
tick(mission, 5)
assert.equal(mission.getSnapshot().collective.changes.length, beforePause)
mission.resume()
mission.reset()
assert.equal(mission.getSnapshot().collective.receivedCount, 0)
assert.equal(mission.getSnapshot().collective.unknownCount, 5)
assert.equal(mission.getSnapshot().collective.changes.length, 0)
assert.equal(mission.getSnapshot().network.reports.length, 0)

console.log('Conciencia Colectiva: recepción, aislamiento, recálculo, justificación, recursos, pausa y reinicio verificados.')
